function parseFrDateToIso(frDate: string): string {
  const parts = frDate.split("/");
  if (parts.length !== 3) return "2026-10-26";
  const [day, month, year] = parts;
  return `${year}-${month.padStart(2, "0")}-${day.padStart(2, "0")}`;
}

function mapSource(channel: string): ApplicationSource {
  const lower = channel.toLowerCase();
  if (lower.includes("hellowork")) return "HelloWork";
  if (lower.includes("indeed")) return "Indeed";
  if (lower.includes("linkedin")) return "LinkedIn";
  if (lower.includes("mstaff") || lower.includes("publique"))
    return "Plateforme MStaff / Publique";
  if (lower.includes("dépôt physique") || lower.includes("main propre"))
    return "Dépôt physique (CV en main propre)";
  if (
    lower.includes("réseau") ||
    lower.includes("cooptation") ||
    lower.includes("stage")
  )
    return "Réseau / Cooptation";
  if (lower.includes("portail") || lower.includes("site"))
    return "Site entreprise / Portail Carrière";
  if (lower.includes("mail") || lower.includes("spontanée"))
    return "Candidature spontanée (Mail)";
  return "Autre";
}

function mapStatus(csvStatus: RawCsvEntry["csvStatus"]): ApplicationStatus {
  switch (csvStatus) {
    case "À contacter":
      return "A_POSTULER";
    case "Candidature envoyée":
    case "Contacté":
      return "ENVOYEE";
    case "Relancé":
      return "RELANCEE";
    case "Refus":
      return "REFUSEE";
  }
}

